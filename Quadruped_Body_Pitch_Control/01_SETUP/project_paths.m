function paths = project_paths()
% PROJECT_PATHS Central path manager for Quadruped Body-Pitch Control Project.
%
% Dynamically discovers the project root directory from the location of this
% file and adds all required project folders to MATLAB's search path.
%
% This function contains NO hardcoded user paths and works across platforms
% and directory relocations.

% Determine location of this file
setup_dir = fileparts(mfilename('fullpath'));
project_root = fileparts(setup_dir);

% Define canonical project folders
subfolders = { ...
    '', ...
    '00_MAIN', ...
    '01_SETUP', ...
    fullfile('02_MODEL', 'dynamics'), ...
    fullfile('02_MODEL', 'parameters'), ...
    fullfile('02_MODEL', 'validation'), ...
    fullfile('03_PHASES', 'Phase_1_Model'), ...
    fullfile('03_PHASES', 'Phase_2_SISO'), ...
    fullfile('03_PHASES', 'Phase_3_P_Controller'), ...
    fullfile('03_PHASES', 'Phase_4_PI_Controller'), ...
    fullfile('03_PHASES', 'Phase_4_5_Disturbance_Frequency'), ...
    fullfile('03_PHASES', 'Phase_4_6_Contact_Loss'), ...
    fullfile('03_PHASES', 'Phase_4_7_Robustness'), ...
    fullfile('03_PHASES', 'Phase_5_Hardware_Realistic'), ...
    fullfile('04_COMMON', 'functions'), ...
    fullfile('04_COMMON', 'utilities'), ...
    fullfile('04_COMMON', 'plotting'), ...
    fullfile('05_SIMULINK', 'models'), ...
    fullfile('05_SIMULINK', 'scripts'), ...
    fullfile('05_SIMULINK', 'data'), ...
    fullfile('06_RESULTS', 'figures'), ...
    fullfile('06_RESULTS', 'tables'), ...
    fullfile('06_RESULTS', 'exported'), ...
    fullfile('07_DATA', 'input'), ...
    fullfile('07_DATA', 'processed'), ...
    '08_DOCUMENTATION', ...
    '09_ARCHIVE' ...
};

% Add existing directories to MATLAB path
for i = 1:numel(subfolders)
    if isempty(subfolders{i})
        folder_path = project_root;
    else
        folder_path = fullfile(project_root, subfolders{i});
    end
    
    if exist(folder_path, 'dir')
        addpath(folder_path);
    end
end

% Return structured paths for programmatic access
if nargout > 0
    paths.root = project_root;
    paths.setup = setup_dir;
    paths.main = fullfile(project_root, '00_MAIN');
    paths.model = fullfile(project_root, '02_MODEL');
    paths.parameters = fullfile(project_root, '02_MODEL', 'parameters');
    paths.dynamics = fullfile(project_root, '02_MODEL', 'dynamics');
    paths.validation = fullfile(project_root, '02_MODEL', 'validation');
    paths.phases = fullfile(project_root, '03_PHASES');
    paths.common = fullfile(project_root, '04_COMMON');
    paths.simulink = fullfile(project_root, '05_SIMULINK');
    paths.results = fullfile(project_root, '06_RESULTS');
    paths.data = fullfile(project_root, '07_DATA');
    paths.docs = fullfile(project_root, '08_DOCUMENTATION');
    paths.archive = fullfile(project_root, '09_ARCHIVE');
end
end
