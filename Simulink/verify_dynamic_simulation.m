function verify_dynamic_simulation()
%VERIFY_DYNAMIC_SIMULATION Deterministic assertions; run in MATLAB.
base=init_3d_simulation();
assert(base.time.dt>0);
% Config overrides must actually propagate.
e=init_3d_simulation(struct('conveyor',struct('height',0.25,'length',5)));
assert(abs(e.conveyor.height-.25)<1e-12);
assert(abs(e.conveyor.length-5)<1e-12);
% Original step and ramp dimensions preserved, centred above original belt.
for j=1:3
    o=base.obstacles(j);
    [z,~,~]=terrain_at_xy(base,o.pos(1),o.pos(2));
    assert(z>base.conveyor.height);
end
% Ramp low/high edges match rendered wedge heights.
o=base.obstacles(2);
[z0,~,~]=terrain_at_xy(base,o.pos(1)-o.size(1)/2,0);
[z1,~,~]=terrain_at_xy(base,o.pos(1)+o.size(1)/2,0);
assert(abs(z0-base.conveyor.height)<1e-12);
assert(abs(z1-(base.conveyor.height+o.size(3)))<1e-12);
% Friction patch must NOT be an elevated obstacle.
o=base.obstacles(4);
[z,mu,~]=terrain_at_xy(base,o.pos(1),o.pos(2));
assert(abs(z-base.conveyor.height)<1e-12);
assert(mu<base.conveyor.friction_mu);
% Telemetry must be generated by stepping, not initialized with samples.
assert(isempty(base.history.time));
base=step_3d_simulation(base);
assert(numel(base.history.time)==1);
assert(abs(base.history.theta(end)-base.state.rpy(2))<1e-12);
assert(abs(base.history.u(end)-base.state.u_pitch)<1e-12);
assert(all(base.state.contact_force>=0));
% Pause freezes both time and history.
base.time.is_paused=true; old_t=base.time.current;
old_n=numel(base.history.time);
base=step_3d_simulation(base);
assert(base.time.current==old_t && numel(base.history.time)==old_n);
% Disturbance is a torque with a finite duration.
base.time.is_paused=false;
base.state.external_torque=.1;
base.state.external_torque_until=base.time.current+2*base.time.dt;
base=step_3d_simulation(base);
assert(abs(base.history.tau_external(end)-.1)<1e-12);
for k=1:3,base=step_3d_simulation(base);end
assert(base.history.tau_external(end)==0);
fprintf('All deterministic engine checks passed.\n');
end
