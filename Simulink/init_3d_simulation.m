function simEngine = init_3d_simulation(cfg)
%INIT_3D_SIMULATION Configurable reduced-order quadruped/conveyor simulation.
% Units: metres, seconds, radians, N, N*m. Obstacle pos is box centre;
% ramp pos is XY centre and Z centre of its bounding box.
if nargin < 1 || isempty(cfg), cfg = struct(); end
assert(isstruct(cfg) && isscalar(cfg), 'cfg must be a scalar struct');
sim_dir = fileparts(mfilename('fullpath'));
proj_root = fileparts(sim_dir);
paths = {sim_dir, fullfile(proj_root,'Robot_Movement','Robot_Parameters'), ...
    fullfile(proj_root,'01_SETUP'), fullfile(proj_root,'02_MODEL','parameters')};
for k = 1:numel(paths)
    if isfolder(paths{k}), addpath(paths{k}); end
end
assert(exist('get_quadruped_geometry','file') == 2, ...
    'get_quadruped_geometry.m must be on the MATLAB path');
g = get_quadruped_geometry();
r = struct('body_length',g.body.length,'body_width',g.body.width, ...
    'body_height',g.body.height,'L1',g.leg.hipToKnee, ...
    'L2',g.leg.kneeToFoot,'standing_height',g.standingHeight, ...
    'hip_positions',g.hipPosition,'nominal_feet',g.nominalFootPosition, ...
    'mass',5.0,'J_pitch',g.J,'B_pitch',g.B,'Kp',0.50, ...
    'Ki',0.20,'u_sat',0.40,'k_torque_to_q',0.05);
c = struct('length',4.0,'width',1.0,'height',0.20,'center',[1.5,0], ...
    'speed',0.10,'running',true,'direction',1.0, ...
    'friction_mu',0.8,'roller_radius',0.05,'texture_offset',0.0, ...
    'stripe_pitch',0.40);
% Obstacle dimensions preserve those supplied in the original engine.
% Solids rest on the belt. A low-friction patch is NOT a raised obstacle.
o(1) = make_obstacle(1,'step','Low Step Platform',[0.80,0], ...
    [0.25,0.60,0.03],[0.95,0.58,0.10],c.height);
o(2) = make_obstacle(2,'ramp','Inclined Ascending Ramp',[1.40,0], ...
    [0.40,0.60,0.04],[0.18,0.78,0.32],c.height);
o(3) = make_obstacle(3,'block','High Clearance Block',[2.10,0], ...
    [0.15,0.50,0.05],[0.92,0.20,0.20],c.height);
o(4) = make_obstacle(4,'patch','Low Friction Hazard Zone',[2.70,0], ...
    [0.35,0.70,0.005],[0.22,0.65,0.96],c.height);
o(4).friction_mu = 0.12; % Configurable scenario assumption, not measured.
ga = struct('frequency',1.0,'step_length',0.10,'step_height',0.04, ...
    'phase_offsets',[0;0.5;0.5;0], 'vx_cmd',0.10,'vy_cmd',0,'wz_cmd',0);
ti = struct('dt',0.005,'current',0,'is_paused',false,'speed_factor',1);
physics = struct('contact_stiffness',1500,'contact_damping',15, ...
    'contact_tolerance',0.002,'slip_mu_scale',0.4, ...
    'terrain_pitch_gain',15,'disturbance_duration',0.5, ...
    'disturbance_torque',0.10,'visual_fps',40);
% Override supported configuration sections, rejecting unknown fields.
if isfield(cfg,'robot'), r = merge_known(r,cfg.robot,'robot'); end
if isfield(cfg,'conveyor'), c = merge_known(c,cfg.conveyor,'conveyor'); end
if isfield(cfg,'gait'), ga = merge_known(ga,cfg.gait,'gait'); end
if isfield(cfg,'time'), ti = merge_known(ti,cfg.time,'time'); end
if isfield(cfg,'physics'), physics = merge_known(physics,cfg.physics,'physics'); end
if isfield(cfg,'obstacles')
    o = cfg.obstacles;
else
    % Keep default solids resting on the belt when belt elevation changes.
    dz_belt = c.height-0.20;
    for j=1:numel(o), o(j).pos(3)=o(j).pos(3)+dz_belt; end
end
allowed = {'robot','conveyor','gait','time','physics','obstacles'};
assert(all(ismember(fieldnames(cfg),allowed)), 'Unknown top-level cfg field');
validateattributes(c.length,{'numeric'},{'scalar','positive','finite'});
validateattributes(c.width,{'numeric'},{'scalar','positive','finite'});
validateattributes(c.height,{'numeric'},{'scalar','nonnegative','finite'});
validateattributes(ti.dt,{'numeric'},{'scalar','positive','finite'});
validateattributes(r.J_pitch,{'numeric'},{'scalar','positive','finite'});
validateattributes(ga.frequency,{'numeric'},{'scalar','positive','finite'});
validateattributes(physics.contact_stiffness,{'numeric'},{'scalar','nonnegative','finite'});
assert(all(size(r.hip_positions)==[4 3]) && all(size(r.nominal_feet)==[4 3]), ...
    'Hip and nominal foot positions must be 4x3');
for k = 1:numel(o)
    assert(all(o(k).size>0) && numel(o(k).pos)==3, 'Invalid obstacle geometry');
    assert(any(strcmp(o(k).type,{'step','ramp','block','patch'})), ...
        'Unsupported obstacle type');
end
s = struct('pos',[c.center(1)-c.length/2+0.70; c.center(2); c.height+r.standing_height], ...
    'rpy',zeros(3,1),'vel',zeros(3,1),'omega',zeros(3,1), ...
    'integrator',0,'q_cmd',zeros(12,1),'foot_pos_world',zeros(4,3), ...
    'contact_states',false(4,1),'contact_loss_leg',0, ...
    'external_torque',0,'external_torque_until',-inf, ...
    'contact_force',zeros(4,1),'terrain_z',c.height*ones(4,1), ...
    'contact_mu',c.friction_mu*ones(4,1),'slip_ratio',0, ...
    'u_pitch',0,'tau_terrain',0,'tau_external',0, ...
    'theta_reference',0,'ik_feasible',true(4,1));
simEngine = struct('robot',r,'conveyor',c,'obstacles',o, ...
    'gait',ga,'time',ti,'physics',physics,'state',s);
simEngine.history = struct('time',[],'theta',[],'theta_ref',[], ...
    'u',[],'q',zeros(12,0),'conveyor_x',[], 'contact_force',zeros(4,0), ...
    'contact_count',[],'slip_ratio',[],'tau_external',[],'terrain_z',zeros(4,0));
fprintf('[3D Simulation Engine] Initialized; dt=%.4g s.\n',ti.dt);
end

function o = make_obstacle(id,type,name,xy,sz,color,belt_z)
o = struct('id',id,'type',type,'name',name, ...
    'pos',[xy(:).' belt_z+sz(3)/2], 'size',sz, ...
    'color',color,'active',true,'friction_mu',NaN);
end

function result = merge_known(base,override,section)
assert(isstruct(override) && isscalar(override), '%s must be struct',section);
names = fieldnames(override);
for i=1:numel(names)
    assert(isfield(base,names{i}), 'Unknown %s field: %s',section,names{i});
    base.(names{i}) = override.(names{i});
end
result = base;
end
